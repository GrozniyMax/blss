package com.blss.blss.security;

/**
 * Перечисление ролей пользователей в системе BLSS.
 * <p>
 * Каждая роль определяет набор прав доступа к различным функциям системы:
 * </p>
 * <ul>
 *     <li><b>ADMIN</b> — полный доступ ко всем функциям системы</li>
 *     <li><b>MANAGER</b> — управление заказами, складом и персоналом</li>
 *     <li><b>CONSULTANT</b> — работа с заказами и клиентами</li>
 *     <li><b>WAREHOUSE</b> — управление складом и поставками</li>
 * </ul>
 */
public enum Role {

    /**
     * <b>Администратор системы</b>
     * <p>
     * Полный доступ ко всем функциям системы:
     * </p>
     * <ul>
     *     <li>Управление пользователями (создание, редактирование, удаление)</li>
     *     <li>Управление точками выдачи заказов (ПВЗ)</li>
     *     <li>Просмотр и редактирование всех заказов</li>
     *     <li>Управление складом и инвентарём</li>
     *     <li>Доступ ко всем API эндпоинтам</li>
     * </ul>
     */
    ADMIN,

    /**
     * <b>Менеджер</b>
     * <p>
     * Управление операционной деятельностью:
     * </p>
     * <ul>
     *     <li>Управление заказами (просмотр, редактирование, отмена)</li>
     *     <li>Управление складом и инвентарём</li>
     *     <li>Управление консультантами</li>
     *     <li>Доступ к точкам выдачи заказов (ПВЗ)</li>
     * </ul>
     * <p>
     * Не имеет доступа к управлению пользователями.
     * </p>
     */
    MANAGER,

    /**
     * <b>Консультант</b>
     * <p>
     * Работа с клиентами и их заказами:
     * </p>
     * <ul>
     *     <li>Создание новых заказов</li>
     *     <li>Просмотр статусов заказов</li>
     *     <li>Обновление статусов заказов</li>
     *     <li>Отметка заказов как полученных (ПВЗ)</li>
     *     <li>Просмотр наличия товаров на складе</li>
     * </ul>
     * <p>
     * Не имеет доступа к управлению складом и пользователями.
     * </p>
     */
    CONSULTANT,

    /**
     * <b>Складской работник</b>
     * <p>
     * Управление складом и поставками:
     * </p>
     * <ul>
     *     <li>Приёмка товаров и обновление инвентаря</li>
     *     <li>Комплектация заказов</li>
     *     <li>Обновление статусов заказов (складские операции)</li>
     *     <li>Отметка заказов как полученных (ПВЗ)</li>
     *     <li>Просмотр наличия товаров на складе</li>
     * </ul>
     * <p>
     * Не имеет доступа к созданию заказов и управлению пользователями.
     * </p>
     */
    WAREHOUSE,

    /**
     * <b>Обычный пользователь (клиент)</b>
     * <p>
     * Базовый доступ для работы с собственными заказами:
     * </p>
     * <ul>
     *     <li>Создание новых заказов</li>
     *     <li>Просмотр статусов собственных заказов по ID</li>
     *     <li>Просмотр содержимого собственных заказов</li>
     * </ul>
     * <p>
     * Не имеет доступа к управлению складом, другими пользователями,
     * редактированию или отмене заказов.
     * </p>
     */
    USER
}
